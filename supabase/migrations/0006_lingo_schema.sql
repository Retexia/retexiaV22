-- ---------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------
create or replace function lingo.owns(p_user bigint) returns boolean
language sql stable security definer set search_path = lingo, public as $$
  select exists (select 1 from lingo.lingo_users where id = p_user and owner_id = auth.uid());
$$;

do $$
declare t text;
begin
  foreach t in array array['lingo_users', 'business_details', 'products', 'customers', 'orders', 'messages', 'fixed_messages'] loop
    execute format('alter table lingo.%I enable row level security', t);
  end loop;
end $$;

drop policy if exists own_account on lingo.lingo_users;
create policy own_account on lingo.lingo_users for select to authenticated
  using (owner_id = (select auth.uid()) or (select public.is_privileged()));
drop policy if exists own_account_update on lingo.lingo_users;
create policy own_account_update on lingo.lingo_users for update to authenticated
  using (owner_id = (select auth.uid())) with check (owner_id = (select auth.uid()));

do $$
declare t text;
begin
  foreach t in array array['business_details', 'products', 'customers', 'orders'] loop
    execute format('drop policy if exists own_rows on lingo.%I', t);
    execute format('create policy own_rows on lingo.%I for all to authenticated using (lingo.owns(lingo_user_id) or (select public.is_privileged())) with check (lingo.owns(lingo_user_id))', t);
  end loop;
end $$;
-- Messages: no chat reading from the browser (the panel shows numbers only); staff may read.
drop policy if exists staff_read on lingo.messages;
create policy staff_read on lingo.messages for select to authenticated using ((select public.is_privileged()));
-- Fixed replies: the shared defaults (no owner) and your own versions.
drop policy if exists read_replies on lingo.fixed_messages;
create policy read_replies on lingo.fixed_messages for select to authenticated
  using (lingo_user_id is null or lingo.owns(lingo_user_id) or (select public.is_privileged()));
drop policy if exists own_replies on lingo.fixed_messages;
create policy own_replies on lingo.fixed_messages for all to authenticated
  using (lingo_user_id is not null and lingo.owns(lingo_user_id)) with check (lingo_user_id is not null and lingo.owns(lingo_user_id));

revoke all on all tables in schema lingo from anon, authenticated;
-- lingo_users: everything except the Evolution connection details.
grant select (id, owner_id, business_name, evolution_instance, owner_phone, staff_name, default_language, content_language,
              followup_hours, delivery_days, active, created_at, updated_at) on lingo.lingo_users to authenticated;
grant update (business_name, owner_phone, staff_name, default_language, content_language, followup_hours, delivery_days, active, updated_at)
  on lingo.lingo_users to authenticated;
grant select, insert, update on lingo.business_details, lingo.products, lingo.fixed_messages to authenticated;
grant delete on lingo.products, lingo.fixed_messages to authenticated;
grant select, update on lingo.customers, lingo.orders to authenticated;
grant select on lingo.messages to authenticated;
grant all on all tables in schema lingo to service_role;
grant usage, select on all sequences in schema lingo to service_role, authenticated;

-- ---------------------------------------------------------------------
-- Panel stats (server-side only)
-- ---------------------------------------------------------------------
create or replace function lingo.panel_customer_stats(p_user bigint)
returns table (customer_id bigint, user_messages bigint, bot_messages bigint, orders bigint, confirmed_orders bigint,
               spent numeric, last_order_status text, last_order_at timestamptz)
language sql stable set search_path = lingo, public as $$
  with m as (
    select customer_id, count(*) filter (where role = 'user') as u, count(*) filter (where role = 'assistant') as a
      from lingo.messages where lingo_user_id = p_user group by customer_id
  ), o as (
    select customer_id, count(*) as n,
           count(*) filter (where status in ('confirmed', 'processing', 'shipped', 'delivered')) as k,
           coalesce(sum(total_price) filter (where status in ('confirmed', 'processing', 'shipped', 'delivered')), 0) as s,
           (array_agg(status order by created_at desc))[1] as last_status,
           max(created_at) as last_at
      from lingo.orders where lingo_user_id = p_user group by customer_id
  )
  select c.id, coalesce(m.u, 0), coalesce(m.a, 0), coalesce(o.n, 0), coalesce(o.k, 0), coalesce(o.s, 0), o.last_status, o.last_at
    from lingo.customers c left join m on m.customer_id = c.id left join o on o.customer_id = c.id
   where c.lingo_user_id = p_user;
$$;

create or replace function lingo.panel_daily_stats(p_user bigint, p_days int default 30)
returns table (day date, customer_messages bigint, active_customers bigint, new_customers bigint, orders bigint, revenue numeric)
language sql stable set search_path = lingo, public as $$
  with d as (
    select generate_series((now() at time zone 'Asia/Colombo')::date - (p_days - 1), (now() at time zone 'Asia/Colombo')::date, interval '1 day')::date as day
  )
  select d.day,
    (select count(*) from lingo.messages m where m.lingo_user_id = p_user and m.role = 'user' and (m.created_at at time zone 'Asia/Colombo')::date = d.day),
    (select count(distinct m.customer_id) from lingo.messages m where m.lingo_user_id = p_user and m.role = 'user' and (m.created_at at time zone 'Asia/Colombo')::date = d.day),
    (select count(*) from lingo.customers c where c.lingo_user_id = p_user and (c.created_at at time zone 'Asia/Colombo')::date = d.day),
    (select count(*) from lingo.orders o where o.lingo_user_id = p_user and o.status <> 'draft' and (o.created_at at time zone 'Asia/Colombo')::date = d.day),
    (select coalesce(sum(o.total_price), 0) from lingo.orders o where o.lingo_user_id = p_user and o.status in ('confirmed', 'processing', 'shipped', 'delivered')
       and (o.created_at at time zone 'Asia/Colombo')::date = d.day)
  from d order by d.day;
$$;

