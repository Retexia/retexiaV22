-- =====================================================================
-- 0006: Retexia Lingo (WhatsApp bot) inside the main Retexia project, in
-- its own schema. Same tables as the original Lingo project, plus:
--   * lingo_users.owner_id: the customer's Retexia login (links the panel);
--   * Row Level Security: owners see their own data, the Retexia team reads all;
--   * the Evolution API key is never readable by customers;
--   * panel stats functions and the public "lingo-products" photo bucket.
-- Safe to run again. After running: Settings → API → Exposed schemas → add "lingo".
-- =====================================================================

create schema if not exists lingo;
grant usage on schema lingo to anon, authenticated, service_role;

create table if not exists lingo.lingo_users (
  id                 bigint generated by default as identity primary key,
  owner_id           uuid references auth.users (id) on delete set null,
  business_name      text not null,
  evolution_instance text not null unique,
  evolution_base_url text not null,
  evolution_apikey   text not null,
  owner_phone        text,
  staff_name         text,
  default_language   text not null default 'singlish' check (default_language in ('si', 'singlish', 'en', 'ta')),
  content_language   text not null default 'singlish' check (content_language in ('si', 'singlish', 'en', 'ta')),
  followup_hours     integer not null default 5,
  delivery_days      integer not null default 3,
  active             boolean not null default true,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
alter table lingo.lingo_users add column if not exists owner_id uuid references auth.users (id) on delete set null;
create index if not exists lingo_users_owner_idx on lingo.lingo_users (owner_id);

